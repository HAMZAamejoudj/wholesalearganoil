export function getLocalizedBlogPost(slug: string, locale: Locale = "en"): BlogPost | undefined {
  const basePost = BLOG_POSTS.find((p) => p.slug === slug);
  if (!basePost) return undefined;

  let localizedOverlay: BlogPostLocalization | undefined;
  if (locale === "fr") localizedOverlay = FR_POSTS[slug];
  else if (locale === "es") localizedOverlay = ES_POSTS[slug];
  else if (locale === "ar") localizedOverlay = AR_POSTS[slug];

  if (!localizedOverlay) return basePost;

  return {
    ...basePost,
    ...localizedOverlay,
    sections: localizedOverlay.sections ?? basePost.sections,
    points: localizedOverlay.points ?? basePost.points,
    faq: localizedOverlay.faq ?? basePost.faq,
  };
}

export function getLocalizedBlogPosts(locale: Locale = "en"): BlogPost[] {
  return BLOG_POSTS.map((p) => getLocalizedBlogPost(p.slug, locale)!);
}

export function getLocalizedBlogPostsByCategory(
  category: BlogCategory,
  locale: Locale = "en"
): BlogPost[] {
  return getLocalizedBlogPosts(locale).filter((p) => p.category === category);
}

export function getLocalizedRelatedBlogPosts(slug: string, locale: Locale = "en"): BlogPost[] {
  return getLocalizedBlogPosts(locale).filter((p) => p.slug !== slug);
}

